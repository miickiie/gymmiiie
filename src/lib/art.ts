import index from '../data/art.json';

export interface ArtEntry {
  n: number;
  src: string;
  url: string;
}

interface ArtPath {
  d: string;
  fill: string;
  fillRule: 'evenodd' | 'nonzero';
  opacity: number;
}

interface ArtData {
  viewBox: string;
  /** Ordered painted paths; a source background and its figure keep distinct fills. */
  frames: ArtPath[][];
}

// Original catalog mappings and reviewed corrections; known conflicts are excluded.
export const ART = index as unknown as Record<string, ArtEntry>;

export function artEntry(slug: string): ArtEntry | undefined {
  const e = ART[slug];
  if (!e || !e.n) return undefined;
  return e;
}

export function artUrl(slug: string): string {
  return `/art/${slug}.svg`;
}

// ---------------------------------------------------------------------------
// Loader — fetches /art/<slug>.svg once and keeps the parsed frames in a
// module cache. The service worker caches the file itself for offline reuse.
// ---------------------------------------------------------------------------
export type { ArtData };

const cache = new Map<string, Promise<ArtData | null>>();

function pathOpacity(value: string | null): number {
  const opacity = Number(value?.trim() || '1');
  return Number.isFinite(opacity) ? Math.max(0, Math.min(1, opacity)) : 1;
}

function parseMotion(svgText: string): ArtData | null {
  try {
    const doc = new DOMParser().parseFromString(svgText, 'image/svg+xml');
    const svg = doc.documentElement;
    if (!svg || svg.querySelector('parsererror')) return null;
    const viewBox = svg.getAttribute('viewBox') || '0 0 512 512';
    const groups = Array.from(svg.querySelectorAll('g[data-frame]'));
    if (!groups.length) return null;
    const frames = groups.map((g) =>
      Array.from(g.querySelectorAll('path'))
        .map((p): ArtPath => ({
          d: p.getAttribute('d') || '',
          fill: p.getAttribute('fill') || 'currentColor',
          fillRule:
            p.getAttribute('fill-rule') === 'evenodd' ? 'evenodd' : 'nonzero',
          opacity: pathOpacity(p.getAttribute('opacity')),
        }))
        .filter((path) => path.d),
    );
    if (frames.some((f) => !f.length)) return null;
    return { viewBox, frames };
  } catch {
    return null;
  }
}

export function loadMotion(slug: string): Promise<ArtData | null> {
  if (!artEntry(slug)) return Promise.resolve(null);
  const hit = cache.get(slug);
  if (hit) return hit;
  const p = fetch(artUrl(slug))
    .then((r) => (r.ok ? r.text() : ''))
    .then((text) => (text ? parseMotion(text) : null))
    .catch(() => null)
    .then((data) => {
      // Offline/transient failures must not poison the cache for this app lifetime.
      if (!data) cache.delete(slug);
      return data;
    });
  cache.set(slug, p);
  return p;
}

// ---------------------------------------------------------------------------
// Instructions (Everkinetic steps/tips keyed by exercise id, generated by
// scripts/build-art.mjs).
// ---------------------------------------------------------------------------
import instructions from '../data/instructions.json';

export interface ExerciseInstructions {
  steps: string[];
  tips?: string[];
  source: string;
  url?: string;
}

const INSTRUCTIONS = instructions as unknown as Record<
  string,
  ExerciseInstructions
>;

export function instructionsOf(
  exerciseId: string,
): ExerciseInstructions | undefined {
  const info = INSTRUCTIONS[exerciseId];
  return info && Array.isArray(info.steps) && info.steps.length
    ? info
    : undefined;
}

// Reviewed corrections take priority over original catalog or custom-authored steps.
export function stepsFor(exercise: { id: string; steps: string[] }): string[] {
  return instructionsOf(exercise.id)?.steps ?? exercise.steps ?? [];
}

export function tipsFor(exercise: { id: string }): string[] {
  return instructionsOf(exercise.id)?.tips ?? [];
}
